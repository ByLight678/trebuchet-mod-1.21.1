function EmitNode($node, [string]$parent, $parentOrigin) {
    if ($node -is [string]) {
        $cube = $elements[$node]
        if ($cube.export -eq $false) { return }
        $pivot = $parentOrigin
        $rot = @(0, 0, 0)
        if ($cube.rotation) { $rot = $cube.rotation; $pivot = $cube.origin }
        $offset = @(($cube.from[0] - $pivot[0]), ($pivot[1] - $cube.to[1]), ($cube.from[2] - $pivot[2]))
        $size = @(($cube.to[0] - $cube.from[0]), ($cube.to[1] - $cube.from[1]), ($cube.to[2] - $cube.from[2]))
        $translation = @(($pivot[0] - $parentOrigin[0]), ($parentOrigin[1] - $pivot[1]), ($pivot[2] - $parentOrigin[2]))
        $rotation = @((-$rot[0] * [Math]::PI / 180), ($rot[1] * [Math]::PI / 180), (-$rot[2] * [Math]::PI / 180))
        $uv = $cube.uv_offset
        $lines.Add("        // $($cube.name)")
        $lines.Add(('        {0}.addOrReplaceChild("{1}", CubeListBuilder.create().texOffs({2}, {3}).addBox({4}, {5}), PartPose.offsetAndRotation({6}, {7}));' -f $parent, $cube.uuid, $uv[0], $uv[1], (Vector $offset), (Vector $size), (Vector $translation), (Vector $rotation)))
        return
    }
    $group = $groups[$node.uuid]
    $name = $group.name
    $o = $group.origin
    $r = $group.rotation
    if (-not $r) { $r = @(0, 0, 0) }
    $translation = @(($o[0] - $parentOrigin[0]), ($parentOrigin[1] - $o[1]), ($o[2] - $parentOrigin[2]))
    $rotation = @((-$r[0] * [Math]::PI / 180), ($r[1] * [Math]::PI / 180), (-$r[2] * [Math]::PI / 180))
    $lines.Add(('        PartDefinition {0} = {1}.addOrReplaceChild("{0}", CubeListBuilder.create(), PartPose.offsetAndRotation({2}, {3}));' -f $name, $parent, (Vector $translation), (Vector $rotation)))
    foreach ($child in $node.children) { EmitNode $child $name $o }
}
